// Independent native-row/input check. It writes no SDK or Codelaya receipts.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
const directory=path.resolve(process.argv[2]);
const read=name=>fs.readFileSync(path.join(directory,name),'utf8');
const events=JSON.parse(read('append-events.json'));
const rows=read('transcript.jsonl').trim().split('\n').map(line=>JSON.parse(line));
const requests=read('requests.jsonl').trim().split('\n').map(line=>JSON.parse(line));
const one=kind=>{const selected=events.filter(event=>event.kind===kind);assert.equal(selected.length,1,kind);return selected[0].value;};
const start=one('session_start'),attempt=one('submit_attempt'),returned=one('submit_return'),append=one('append_return');
assert.equal(events.filter(event=>event.kind==='submit_uncertain').length,0);
for(const value of [attempt,returned,append,one('turn_start'),one('turn_complete'),one('session_end')])assert.equal(value.sessionId,start.sessionId);
assert.equal(attempt.payload,'AIKIT_APPEND_CANDIDATE: preserve exact 雪\nreview');
assert.equal(returned.result.text,attempt.payload);
assert.equal(returned.result.origin.kind,'plugin');
assert.equal(returned.result.origin.name,'aikit-mod-feasibility');
assert.equal(append.event.door,'prompt');
assert.deepEqual(append.event.origin,returned.result.origin);
assert.equal(append.result.uuid,append.event.uuid);
assert.match(append.result.uuid,/^[a-f0-9-]{36}$/);
assert.equal(append.result.message.type,'user');
assert.equal(append.result.message.role,'user');
const text=content=>{if(typeof content==='string')return content;assert(Array.isArray(content));assert(content.every(block=>block.type==='text'&&typeof block.text==='string'));return content.map(block=>block.text).join('');};
assert.equal(text(append.result.message.content),attempt.payload);
const persisted=rows.filter(row=>row.uuid===append.result.uuid);
assert.equal(persisted.length,1);
assert.equal(persisted[0].type,'user');
assert.equal(persisted[0].message.role,'user');
assert.equal(text(persisted[0].message.content),attempt.payload);
const main=requests.filter(request=>request.method==='POST'&&request.body?.tools?.some(tool=>tool.name==='mcp__aikit-mod-feasibility__append_probe'));
assert.equal(main.length,1);
assert.equal(JSON.parse(main[0].body.metadata.user_id).session_id,start.sessionId);
assert.equal(JSON.stringify(main[0].body.messages).split(JSON.stringify(attempt.payload).slice(1,-1)).length-1,1);
const completed=one('turn_complete').event;
assert.equal(completed.turnId,one('turn_start').event.turnId);
assert.equal(completed.reason,'answer');assert.equal(completed.isAborted,false);
const hashes=Object.fromEntries(['append-events.json','transcript.jsonl','requests.jsonl'].map(name=>[name,createHash('sha256').update(read(name)).digest('hex')]));
console.log(JSON.stringify({passed:true,scope:'Linux native stored-row acknowledgement candidate with scripted replies',session_id:start.sessionId,row_uuid:append.result.uuid,main_requests:main.length,stored_payload_sha256:createHash('sha256').update(attempt.payload).digest('hex'),windows_qualified:false,production_acknowledgement_qualified:false,production_consumption_qualified:false,sdk_receipt_mutated:false,hashes},null,2));
